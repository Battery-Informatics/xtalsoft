def bool_str(val: bool) -> str:
    """Format boolean as lowercase 'true' or 'false' for XtalOpt parser."""
    return "true" if val else "false"


def generate_xtalopt_in_content(config: XtalOptExperimentConfig) -> str:
    """Construct the full text of a valid xtalopt.in file for XtalOpt v15.

    Organized strictly into the 4 primary sections parsed by XtalOpt:
    1. Initialization settings
    2. Search settings
    3. Queue interface settings
    4. Optimizer settings
    """
    lines = [
        "# ====================================================================",
        "# XtalOpt v15 Input Deck generated by XtalOpt Web Workbench",
        "# ====================================================================",
        "",
        "# Initialization settings",
        "  # Composition settings",
        f"    chemicalFormulas = {config.chemical_formulas}",
        "",
    ]

    # Reference energies if specified
    if config.reference_energies:
        lines.append(f"    referenceEnergies = {config.reference_energies}")

    # VC search
    lines.append(f"    vcSearch = {bool_str(config.vc_search)}")
    lines.append(f"    minAtoms = {config.min_atoms}")
    lines.append(f"    maxAtoms = {config.max_atoms}")
    lines.append("")

    # Lattice constraints
    lat = config.lattice
    lines.extend([
        "  # Lattice constraints",
        "    # Lattice length minima and maxima (Angstroms)",
        f"      aMin = {lat.a_min:.4f}",
        f"      bMin = {lat.b_min:.4f}",
        f"      cMin = {lat.c_min:.4f}",
        f"      aMax = {lat.a_max:.4f}",
        f"      bMax = {lat.b_max:.4f}",
        f"      cMax = {lat.c_max:.4f}",
        "",
        "    # Lattice angle minima and maxima (Degrees)",
        f"      alphaMin = {lat.alpha_min:.2f}",
        f"      betaMin  = {lat.beta_min:.2f}",
        f"      gammaMin = {lat.gamma_min:.2f}",
        f"      alphaMax = {lat.alpha_max:.2f}",
        f"      betaMax  = {lat.beta_max:.2f}",
        f"      gammaMax = {lat.gamma_max:.2f}",
        "",
    ])

    # Volume limits
    vol = config.volume
    lines.extend([
        "  # Volume limits",
        f"    minVolume = {vol.min_volume:.2f}",
        f"    maxVolume = {vol.max_volume:.2f}",
    ])
    if vol.min_volume_scale > 0.0 or vol.max_volume_scale > 0.0:
        lines.append(f"    minVolumeScale = {vol.min_volume_scale:.2f}")
        lines.append(f"    maxVolumeScale = {vol.max_volume_scale:.2f}")
    if vol.elemental_volumes:
        lines.append(f"    elementalVolumes = {vol.elemental_volumes}")
    lines.append("")

    # Atomic radii & Interatomic distances
    rad = config.radii
    lines.extend([
        "  # Atomic radii / Interatomic Distances",
        f"    usingScaledIADs = {bool_str(rad.using_scaled_iads)}",
        f"    radiiScalingFactor = {rad.radii_scaling_factor:.2f}",
        f"    minRadius = {rad.min_radius:.2f}",
        f"    usingCustomIADs = {bool_str(rad.using_custom_iads)}",
        f"    checkIADPostOptimization = {bool_str(rad.check_iad_post_optimization)}",
    ])
    for ciad in rad.custom_iads:
        lines.append(f"    customIAD = {ciad}")
    lines.append("")

    # Symmetry / RandSpg
    lines.append(f"    usingRandSpg = {bool_str(config.using_rand_spg)}")
    if config.forced_spgs:
        lines.append(f"    forcedSpgs = {config.forced_spgs}")
    lines.extend([
        "",
        "# End of initialization settings",
        "",
        "# Search settings",
    ])

    # Search parameters
    srch = config.search
    lines.extend([
        f"    numInitial = {srch.num_initial}",
        f"    parentsPoolSize = {srch.parents_pool_size}",
        f"    limitRunningJobs = {bool_str(srch.limit_running_jobs)}",
        f"    runningJobLimit = {srch.running_job_limit}",
        f"    continuousStructures = {srch.continuous_structures}",
        f"    maxNumStructures = {srch.max_num_structures}",
        f"    jobFailLimit = {srch.job_fail_limit}",
        f"    jobFailAction = {srch.job_fail_action}",
        f"    softExit = {bool_str(srch.soft_exit)}",
        f"    hardExit = {bool_str(srch.hard_exit)}",
        "",
    ])

    # Mutation operator weights & parameters
    mut = config.mutation
    lines.extend([
        "  # Mutation operators",
        f"    weightCrossover = {mut.weight_crossover}",
        f"    weightStripple = {mut.weight_stripple}",
        f"    weightPermustrain = {mut.weight_permustrain}",
        f"    weightPermutomic = {mut.weight_permutomic}",
        f"    weightPermucomp = {mut.weight_permucomp}",
        f"    randomSuperCell = {mut.random_supercell}",
        "",
        "  # Stripple options",
        f"    strippleAmplitudeMin = {mut.stripple_amplitude_min:.2f}",
        f"    strippleAmplitudeMax = {mut.stripple_amplitude_max:.2f}",
        f"    strippleNumWavesAxis1 = {mut.stripple_num_waves_axis1}",
        f"    strippleNumWavesAxis2 = {mut.stripple_num_waves_axis2}",
        f"    strippleStrainStdevMin = {mut.stripple_strain_stdev_min:.2f}",
        f"    strippleStrainStdevMax = {mut.stripple_strain_stdev_max:.2f}",
        "",
        "  # Permustrain options",
        f"    permustrainNumExchanges = {mut.permustrain_num_exchanges}",
        f"    permustrainStrainStdevMax = {mut.permustrain_strain_stdev_max:.2f}",
        "",
        "  # Crossover options",
        f"    crossoverMinContribution = {mut.crossover_min_contribution}",
        f"    crossoverCuts = {mut.crossover_cuts}",
        "",
    ])

    # Tolerances
    tol = config.tolerances
    lines.extend([
        "  # Similarity & space group tolerances",
        f"    xtalcompToleranceLength = {tol.xtalcomp_tolerance_length:.2f}",
        f"    xtalcompToleranceAngle = {tol.xtalcomp_tolerance_angle:.2f}",
        f"    rdfTolerance = {tol.rdf_tolerance:.2f}",
        f"    rdfCutoff = {tol.rdf_cutoff:.2f}",
        f"    rdfSigma = {tol.rdf_sigma:.4f}",
        f"    rdfNumBins = {tol.rdf_num_bins}",
        f"    spglibTolerance = {tol.spglib_tolerance:.4f}",
        "",
        "  # Output settings",
        f"    verboseOutput = {bool_str(config.verbose_output)}",
        f"    debugOutput = {bool_str(config.debug_output)}",
        f"    saveHullSnapshots = {bool_str(config.save_hull_snapshots)}",
        "",
        "# End of search settings",
        "",
        "# Queue interface settings",
    ])

    # Queue interface
    opt_cfg = config.optimizer_cfg
    lines.extend([
        f"  templatesDirectory = {opt_cfg.templates_directory}",
        f"  queueInterface = {opt_cfg.queue_interface}",
        f"  localWorkingDirectory = {opt_cfg.local_working_directory}",
        f"  logErrorDirectories = {bool_str(opt_cfg.log_error_directories)}",
        f"  numOptimizationSteps = {opt_cfg.num_optimization_steps}",
        "",
        "# End of queue interface settings",
        "",
        "# Optimizer settings",
        f"  optimizer = {opt_cfg.optimizer}",
        f"  directRunCommand = {opt_cfg.direct_run_command}",
        f"  ginTemplates = {opt_cfg.gin_templates}",
        "",
        "# End of optimizer settings",
        "",
    ])

    return "\n".join(lines)


def get_default_gulp_template_for_formula(formula: str) -> str:
    """Select appropriate default GULP template based on chemical formula."""
    cleaned = formula.upper().replace(" ", "")
    # TiO / TiO2 systems
    if "TI" in cleaned and "O" in cleaned and len(set(cleaned) - set("0123456789-TIO,")) == 0:
        return DEFAULT_GULP_TIO2_TEMPLATE
    return DEFAULT_GENERIC_GULP_TEMPLATE


def create_experiment_workspace(
    exp_id: str,
    config: XtalOptExperimentConfig,
    base_runs_dir: Optional[Path] = None,
) -> Path:
    """Scaffold an isolated runs/<exp_id>/ folder and populate required input files.

    Creates:
    - runs/<exp_id>/
    - runs/<exp_id>/xtalopt.in
    - runs/<exp_id>/templates/gulp/gin1
    - runs/<exp_id>/localWorkingDirectory/
    - runs/<exp_id>/config.json (JSON serialized backup of the request)

    Returns the Path to the created experiment directory.
    """
    runs_root = base_runs_dir or settings.RUNS_DIR
    exp_dir = runs_root / exp_id
    exp_dir.mkdir(parents=True, exist_ok=True)

    # 1. Create templates directory
    templates_dir = exp_dir / "templates" / "gulp"
    templates_dir.mkdir(parents=True, exist_ok=True)

    # 2. Write gin1 template file
    gin_template_path = templates_dir / "gin1"
    template_content = (
        config.optimizer_cfg.custom_gulp_template
        if config.optimizer_cfg.custom_gulp_template
        else get_default_gulp_template_for_formula(config.chemical_formulas)
    )
    gin_template_path.write_text(template_content, encoding="utf-8")
    logger.info("Generated GULP template at %s", gin_template_path)

    # 3. Create localWorkingDirectory
    local_work_dir = exp_dir / "localWorkingDirectory"
    local_work_dir.mkdir(parents=True, exist_ok=True)

    # 4. Generate and write xtalopt.in
    xtalopt_in_path = exp_dir / "xtalopt.in"
    in_deck = generate_xtalopt_in_content(config)
    xtalopt_in_path.write_text(in_deck, encoding="utf-8")
    logger.info("Generated xtalopt.in at %s", xtalopt_in_path)

    # 5. Save structured JSON copy
    config_json_path = exp_dir / "config.json"
    config_json_path.write_text(
        json.dumps(config.model_dump(), indent=2),
        encoding="utf-8"
    )

    return exp_dir

